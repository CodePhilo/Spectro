BANNER_BG, TITLE, BODY, ACCENT = "#f0efec", "#0b0b0b", "#52514e", "#2a78d6"


class Shooter:
    def __init__(self, out: Path, app: QApplication):
        self.out, self.app = out, app
        self.entries: list[dict] = []
        out.mkdir(parents=True, exist_ok=True)

    def shot(self, widget, key: str, title: str, benefit: str, steps: str = "") -> None:
        widget.show()
        for _ in range(3):
            self.app.processEvents()
        pm = widget.grab()
        banner_h = 92
        full = QPixmap(pm.width(), pm.height() + banner_h)
        full.fill(QColor(BANNER_BG))
        p = QPainter(full)
        p.fillRect(QRect(0, 0, 6, banner_h), QColor(ACCENT))
        f = QFont()
        f.setPointSize(15)
        f.setBold(True)
        p.setFont(f)
        p.setPen(QColor(TITLE))
        n = len(self.entries) + 1
        p.drawText(QRect(22, 8, pm.width() - 40, 30), Qt.AlignLeft | Qt.AlignVCenter,
                   f"{n}. {title}")
        f.setPointSize(10)
        f.setBold(False)
        p.setFont(f)
        p.setPen(QColor(BODY))
        p.drawText(QRect(22, 40, pm.width() - 40, 50), Qt.AlignLeft | Qt.TextWordWrap,
                   f"Benefit: {benefit}" + (f"   ·   How: {steps}" if steps else ""))
        p.drawPixmap(0, banner_h, pm)
        p.end()
        name = f"{n:02d}_{key}.png"
        full.save(str(self.out / name))
        compact_png(self.out / name)
        self.entries.append({"file": name, "title": title, "benefit": benefit, "steps": steps})
        print(f"  saved {name}")

    def write_index(self) -> None:
        cards = "\n".join(
            f"<figure><img src='{e['file']}' alt='{html.escape(e['title'])}'>"
            f"<figcaption><b>{i}. {html.escape(e['title'])}</b><br>"
            f"<span>{html.escape(e['benefit'])}</span>"
            + (f"<br><i>How: {html.escape(e['steps'])}</i>" if e["steps"] else "")
            + "</figcaption></figure>" for i, e in enumerate(self.entries, 1))
        (self.out / "index.html").write_text(f"""<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>Spectro workflows</title>
<style>body{{font-family:Segoe UI,Arial,sans-serif;margin:24px;background:#fcfcfb;color:#0b0b0b}}
h1{{margin:0 0 4px}} p.lead{{color:#52514e;max-width:900px}}
figure{{margin:28px 0;border:1px solid #e3e2de;border-radius:8px;overflow:hidden;background:#fff}}
img{{width:100%;display:block}} figcaption{{padding:10px 14px;color:#52514e}}
figcaption b{{color:#0b0b0b}}</style></head><body>
<h1>Spectro — workflows</h1><p class="lead">Screenshots generated automatically by
<code>tools/workflow_screenshots.py</code> on the bundled demo project (paracetamol / caffeine /
aspirin; simulated spectra with realistic noise). How to apply each individual method is in the
<a href="../methods/index.html">method guide</a>.</p>{cards}</body></html>""", encoding="utf-8")
        md = ["# Spectro — workflows", "",
              "Generated by `python tools/workflow_screenshots.py` on the demo project "
              "(simulated spectra with realistic noise). How to apply each individual method is "
              "in the [method guide](../methods/README.md).", ""]
        for i, e in enumerate(self.entries, 1):
            md += [f"## {i}. {e['title']}", "", f"**Benefit:** {e['benefit']}", ""]
            if e["steps"]:
                md += [f"*How:* {e['steps']}", ""]
            md += [f"![{e['title']}]({e['file']})", ""]
        (self.out / "README.md").write_text("\n".join(md), encoding="utf-8")


