    # 9–10
    def studies(self, d):
        from spectro.core.spectrum import Spectrum
        from spectro.ui.dialogs_methods import RobustnessDialog
        tid = self.p.trials()[0]["id"]
        tab = self.p.spectrum(self.named("Panadol Extra tablet 1 (label claim)"))
        par10 = self.p.spectrum(self.named("PAR 10 ug/mL"))
        spikes = []
        rng = np.random.default_rng(7)  # measurement noise + pipetting error of each solution
        for i, a in enumerate([0, 0, 4, 8, 12]):
            y = (tab.y * rng.normal(1, 0.002) + a / 10 * np.interp(tab.x, par10.x, par10.y)
                 * rng.normal(1, 0.004) + rng.normal(0, 0.0004, tab.x.size)
                 + rng.normal(0, 0.001))
            s = Spectrum(tab.x, y,
                         name=f"Tablet 1 + {a} µg/mL PAR (simulated spike {i + 1})",
                         concentrations={"PAR": float(a)})
            spikes.append(self.p.add_spectrum(s, tid, role="sample", note="simulated spike"))
        d.test.populate([r for r in self.p.records() if r.kind == "raw"], set(spikes))
        d._std_addition()
        self.s.shot(d, "standard_addition", "Standard addition inside the method",
                    "checks accuracy in the real matrix: recovery of each spike and the "
                    "extrapolated content, with the same calibrated method.",
                    "Standard addition… (spiked samples)")
        mixes = self.ids(lambda r: r.kind == "raw" and r.role == "mixture")
        rob = RobustnessDialog(d, d.method, self.p.spectra(d.cal_ids), self.p.spectra(mixes))
        rob.resize(1050, 640)
        rob._run()
        self.s.shot(rob, "robustness", "Robustness study in one click",
                    "each parameter (λ, Δλ, plateau, window…) is varied by ±Δ, re-calibrated and "
                    "re-assayed; the % deviation shows whether the method is robust (ICH Q2).",
                    "Robustness…")

