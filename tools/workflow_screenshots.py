def select(win, ids):
    win.tree.clearSelection()
    stack = [win.tree.invisibleRootItem()]
    while stack:
        node = stack.pop()
        for i in range(node.childCount()):
            ch = node.child(i)
            if ch.data(0, Qt.UserRole) in ids:
                ch.setSelected(True)
            stack.append(ch)


def check_only(lst, ids):
    for i in range(lst.count()):
        it = lst.item(i)
        it.setCheckState(Qt.Checked if it.data(Qt.UserRole) in ids else Qt.Unchecked)


