def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=str(ROOT / "docs" / "workflows"))
    ap.add_argument("--only", default="", help="comma-separated workflow names")
    args = ap.parse_args(argv)
    app = QApplication.instance() or QApplication(sys.argv[:1])
    app.setStyle("Fusion")
    shooter = Shooter(Path(args.out), app)
    only = [w for w in args.only.split(",") if w]
    failures = []
    with tempfile.TemporaryDirectory() as tmp:
        demo = Demo(shooter, Path(tmp))
        uni = None
        for name in WORKFLOWS:
            if only and name not in only and not (name == "univariate" and "studies" in only):
                continue
            print(f"{name}…")
            try:
                res = getattr(demo, name)()
                if name == "univariate":
                    uni = res
                    if not only or "studies" in only:
                        demo.studies(uni)
            except Exception:
                failures.append(name)
                traceback.print_exc()
        demo.win.close_project()
    shooter.write_index()
    print(f"\n{len(shooter.entries)} screenshots + index.html + README.md in {args.out}")
    if failures:
        print("FAILED:", ", ".join(failures))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
