    # 11c
    def progressive(self):
        """Apply the amplitude-centering method proposed by the optimizer."""
        from PySide6.QtWidgets import QTableWidgetItem
        from spectro.ui.dialogs_methods import ProgressiveDialog
        opt = getattr(self, "opt_ternary", None)
        if opt is None:
            self.optimizer()
            opt = self.opt_ternary
        best = min((c for comp in opt.inp.compounds for c in opt.result["ranked"][comp]
                    if c.family == "amplitude_centering" and not c.error),
                   key=lambda c: c.score)
        m = best.model
        z = m["divisor_compound"]
        d = ProgressiveDialog(self.win)
        d.resize(1300, 1000)
        for i in range(d.ac_comps.count()):
            it = d.ac_comps.item(i)
            it.setCheckState(Qt.Checked if it.text() in m["compounds"] else Qt.Unchecked)
        d.ac_div.setCurrentIndex(d.ac_div.findData(opt.div_boxes[z].currentData()))
        d.ac_divc.setCurrentText(z)
        d.ac_w.setValue(m["wavelength"])
        d.ac_plateau.setChecked(bool(m["plateau"]))
        for i, (c, df) in enumerate(m["differences"].items()):
            for j, v in enumerate((c, f"{df['w1']:.1f}", f"{df['w2']:.1f}",
                                   df.get("factor_from") or "")):
                d.ac_diff.setItem(i, j, QTableWidgetItem(v))
        d.ac_sub.setCurrentText(m["subtract"])
        check_only(d.ac_std, [i for c in m["compounds"] for i in opt.std_ids[c]])
        check_only(d.ac_mix, self.ids(lambda r: r.kind == "raw" and r.role == "validation"))
        d._run_ac()
        self.s.shot(d, "progressive", "Progressive resolution: amplitude centering",
                    "AAC / MACM / RIDSS / CV-AD resolve all three drugs from ONE ratio spectrum "
                    "at ONE wavelength; here with the settings the optimizer proposed. Saved "
                    "like any method and applied to new samples.",
                    "Methods → Progressive resolution")

